bool InRanges(const CodePointRange* ranges, size_t count, char32_t c) {
    size_t lo = 0, hi = count;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (c < ranges[mid].first)
            hi = mid;
        else if (c > ranges[mid].last)
            lo = mid + 1;
        else
            return true;
    }
    return false;
}

